const PALETTE = [
  '#3b82f6',
  '#10b981',
  '#f59e0b',
  '#ef4444',
  '#8b5cf6',
  '#ec4899',
  '#14b8a6',
  '#f97316',
  '#6366f1',
  '#84cc16',
  '#06b6d4',
  '#d946ef',
];

export function getCategoryColor(categoryName: string): string {
  if (!categoryName) return '#94a3b8';

  let hash = 0;
  for (let i = 0; i < categoryName.length; i++) {
    hash = categoryName.charCodeAt(i) + ((hash << 5) - hash);
  }

  hash = Math.abs(hash);

  return PALETTE[hash % PALETTE.length];
}
